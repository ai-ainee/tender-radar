_COUNTRY_CTX = {
    "aliases": {},   # {country_lower: {alias1, alias2, ...}}
    "tlds": {},      # {".in": "India", ".gov.in": "India", ...}
    "cache_key": "",
}

def generate_country_context(llm, countries):
    """LLM generates country aliases + TLDs from Settings' Target Countries list.

    Runs once per execution. Falls back to name-only matching if LLM unavailable.
    """
    if not countries:
        _COUNTRY_CTX["aliases"] = {}
        _COUNTRY_CTX["tlds"] = {}
        _COUNTRY_CTX["cache_key"] = ""
        return

    cache_key = "|".join(sorted(str(c).lower() for c in countries if c))
    if _COUNTRY_CTX.get("cache_key") == cache_key:
        return                                   # already generated this run

    country_list = "\n".join(f"- {c}" for c in countries if c)
    prompt = f"""You are a geography reference API. For each country below, return:
  1. Common aliases and abbreviations used in news articles and URLs
  2. Common domain extensions (TLDs) used for that country's websites
     (include both generic and government TLDs)

Countries:
{country_list}

Rules:
- Aliases: lowercase only, no duplicates, 2-4 per country
- TLDs: always start with a dot, sorted longest-first (specific before generic)
- Only include TLDs actually used for that country
- For India: include .in, .gov.in, .co.in, .nic.in, .org.in
- For UAE: include .ae, .gov.ae
- For USA: include .us, .gov (no state-level TLDs)

Return ONLY JSON: {{"aliases": {{"<Country Name>": ["alias1", "alias2"]}}, "tlds": {{"<Country Name>": [".tld1", ".tld2"]}}}}"""

    data = None
    if llm and llm.available():
        data = llm.generate_json(prompt, validator=lambda d: isinstance(d, dict) and "aliases" in d)

    if not isinstance(data, dict):
        log.warning("country_context: LLM unavailable — falling back to name-only matching")
        _COUNTRY_CTX["aliases"] = {str(c).lower(): {str(c).lower()} for c in countries if c}
        _COUNTRY_CTX["tlds"] = {}
        _COUNTRY_CTX["cache_key"] = cache_key
        return

    aliases_in = data.get("aliases") or {}
    tlds_in = data.get("tlds") or {}

    aliases = {}
    for country, alias_list in aliases_in.items():
        if not isinstance(alias_list, list):
            continue
        c_norm = str(country).lower().strip()
        al = {str(a).lower().strip() for a in alias_list if a}
        al.add(c_norm)
        aliases[c_norm] = al

    tlds = {}
    for country, tld_list in tlds_in.items():
        if not isinstance(tld_list, list):
            continue
        for t in tld_list:
            if t and str(t).startswith("."):
                tlds[str(t).lower()] = str(country)

    _COUNTRY_CTX["aliases"] = aliases
    _COUNTRY_CTX["tlds"] = tlds
    _COUNTRY_CTX["cache_key"] = cache_key
    log.info(f"country_context: {len(aliases)} countr(y/ies), "
             f"{sum(len(a) for a in aliases.values())} aliases, {len(tlds)} TLDs")


def _norm_country_(c):
    """Normalizes a country name to canonical lowercase form via aliases."""
    c = str(c or "").strip().lower()
    if not c:
        return ""
    aliases = _COUNTRY_CTX.get("aliases") or {}
    if c in aliases:
        return c
    for country, alias_set in aliases.items():
        if c in alias_set:
            return country
    return c


def country_from_url(url):
    """Infers country from URL TLD using runtime-generated TLD map."""
    host = urlparse(url or "").netloc.lower()
    tlds = _COUNTRY_CTX.get("tlds") or {}
    for tld in sorted(tlds.keys(), key=lambda x: -len(x)):
        if host.endswith(tld):
            return tlds[tld]
    return ""


